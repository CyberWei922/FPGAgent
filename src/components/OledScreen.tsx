export function resolveGlyphBitmap(code: number): readonly number[] | null {
  const byte = code & 0xff;
  if (byte === 0) return null;
  if (byte >= 0x20 && byte <= 0x7e) return ASCII_FONT_8X8[byte] ?? null;
  if (byte >= 0x80 && byte <= 0x9f) return TILE_FONT_8X8[byte] ?? TILE_FONT_8X8[0x80];
  return null;
}

// Render at 4px pitch per OLED dot (512x256 backing store for crisp 128x64 dot matrix)
const PIXEL_PITCH = 4;
const PIXEL_SIZE = 3;
const CANVAS_W = BOARD_SCREEN_COLS * 8 * PIXEL_PITCH;
const CANVAS_H = BOARD_SCREEN_ROWS * 8 * PIXEL_PITCH;

export function OledScreen({
  buffer,
  tint = 'white',
  ariaLabel,
}: {
  buffer?: number[];
  tint?: OledTint;
  ariaLabel?: string;
}) {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    const palette = OLED_TINT_CONFIG[tint];
    ctx.fillStyle = palette.bg;
    ctx.fillRect(0, 0, CANVAS_W, CANVAS_H);

    // Subtle unlit OLED dot matrix substrate
    ctx.fillStyle = palette.off;
    for (let py = 0; py < BOARD_SCREEN_ROWS * 8; py++) {
      const yPos = py * PIXEL_PITCH;
      for (let px = 0; px < BOARD_SCREEN_COLS * 8; px++) {
        ctx.fillRect(px * PIXEL_PITCH, yPos, PIXEL_SIZE, PIXEL_SIZE);
      }
    }

    if (!buffer || buffer.length === 0) return;

    // Pass 1: subtle phosphor bloom for lit pixels
    ctx.fillStyle = palette.glow;
    for (let row = 0; row < BOARD_SCREEN_ROWS; row++) {
      for (let col = 0; col < BOARD_SCREEN_COLS; col++) {
        const glyph = resolveGlyphBitmap(buffer[row * BOARD_SCREEN_COLS + col] ?? 0);
        if (!glyph) continue;
        const baseX = col * 8;
        const baseY = row * 8;
        for (let gy = 0; gy < 8; gy++) {
          const bits = glyph[gy];
          if (!bits) continue;
          for (let gx = 0; gx < 8; gx++) {
            if (bits & (0x80 >> gx)) {
              ctx.fillRect(
                (baseX + gx) * PIXEL_PITCH - 1,
                (baseY + gy) * PIXEL_PITCH - 1,
                PIXEL_SIZE + 2,
                PIXEL_SIZE + 2,
              );
            }
          }
        }
      }
    }

    // Pass 2: crisp monochrome OLED pixels
    ctx.fillStyle = palette.lit;
    for (let row = 0; row < BOARD_SCREEN_ROWS; row++) {
      for (let col = 0; col < BOARD_SCREEN_COLS; col++) {
        const glyph = resolveGlyphBitmap(buffer[row * BOARD_SCREEN_COLS + col] ?? 0);
        if (!glyph) continue;
        const baseX = col * 8;
        const baseY = row * 8;
        for (let gy = 0; gy < 8; gy++) {
          const bits = glyph[gy];
          if (!bits) continue;
          for (let gx = 0; gx < 8; gx++) {
            if (bits & (0x80 >> gx)) {
              ctx.fillRect(
                (baseX + gx) * PIXEL_PITCH,
                (baseY + gy) * PIXEL_PITCH,
                PIXEL_SIZE,
                PIXEL_SIZE,
              );
            }
          }
        }
      }
    }
  }, [buffer, tint]);

  return (
    <div className="oled-bezel" data-tint={tint}>
      <canvas
        ref={canvasRef}
        className="oled-canvas"
        width={CANVAS_W}
        height={CANVAS_H}
        role="img"
        aria-label={ariaLabel ?? '16×8 Monochrome OLED Display (128×64)'}
      />
    </div>
  );
}
